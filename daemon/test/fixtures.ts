const created: string[] = [];

// The tests poll these files while fake engines write them, so a reader must never see a half-written one.
export function writeWhole(path: string, data: string): void {
  const staging = join(dirname(path), `.${basename(path)}.partial`);
  writeFileSync(staging, data);
  renameSync(staging, path);
}

export function tempDir(prefix: string): string {
  const dir = mkdtempSync(join(tmpdir(), prefix));
  created.push(dir);
  return dir;
}

export function removeTempDirs(): void {
  for (const dir of created.splice(0)) rmSync(dir, { recursive: true, force: true });
}

export interface Call {
  args: readonly string[];
  input?: string | Buffer;
}

export function ok(stdout = ""): CommandResult {
  return { code: 0, stdout: Buffer.from(stdout), stderr: "" };
}

export function fakeDocker(overrides: (args: readonly string[]) => CommandResult | null = () => null, instanceId?: string) {
  const calls: Call[] = [];
  const runner: DockerRunner = async (args, options: RunOptions = {}) => {
    calls.push({ args, input: options.input });
    const custom = overrides(args);
    if (custom) return custom;
    if (args[1] === "inspect" && args.some((arg) => arg.includes('"hive.instance"'))) return ok(instanceId ?? loadOrCreateInstanceId());
    if (args[0] === "exec" && args.includes("nft")) return ok(RULESET);
    if (args[0] === "exec" && args.includes("/etc/resolv.conf")) return ok(RESOLV_CONF);
    if (args[0] === "exec" && args.includes("route")) return ok(ROUTES);
    if (args[0] === "inspect") return ok("true");
    if (args[0] === "port") return ok("127.0.0.1:61234");
    return ok();
  };
  return { calls, runner };
}

export interface CommandCall {
  file: string;
  args: readonly string[];
  options: CommandOptions;
}

export function fakeCommands(reply: (call: CommandCall) => Partial<CommandOutput> = () => ({})) {
  const calls: CommandCall[] = [];
  const runner: CommandRunner = async (file, args, options = {}) => {
    const call = { file, args, options };
    calls.push(call);
    return { code: 0, stdout: "", stderr: "", timedOut: false, overflowed: false, ...reply(call) };
  };
  return { calls, runner };
}

export interface Reply {
  status: number;
  body: unknown;
}

function isAddress(value: unknown): value is AddressInfo {
  return typeof value === "object" && value !== null && "port" in value;
}

export function freePort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const probe = createServer();
    probe.once("error", reject);
    probe.listen(0, "127.0.0.1", () => {
      const address = probe.address();
      probe.close(() => (isAddress(address) ? resolve(address.port) : reject(new Error("no port"))));
    });
  });
}

export function call(port: number, method: string, path: string, options: { token?: string; host?: string; body?: unknown; headers?: OutgoingHttpHeaders } = {}): Promise<Reply> {
  const headers: OutgoingHttpHeaders = { host: options.host ?? `127.0.0.1:${port}`, "content-type": "application/json", ...options.headers };
  if (options.token) headers.authorization = `Bearer ${options.token}`;
  return new Promise((resolve, reject) => {
    const outgoing = request({ host: "127.0.0.1", port, method, path, headers }, (response) => {
      let raw = "";
      response.on("data", (chunk: Buffer) => (raw += chunk.toString("utf8")));
      response.on("end", () => {
        let body: unknown = raw;
        try {
          body = JSON.parse(raw);
        } catch {
          body = raw;
        }
        resolve({ status: response.statusCode ?? 0, body });
      });
    });
    outgoing.on("error", reject);
    if (options.body !== undefined) outgoing.write(JSON.stringify(options.body));
    outgoing.end();
  });
}

export function field(value: unknown, key: string): unknown {
  return typeof value === "object" && value !== null ? Object.entries(value).find(([name]) => name === key)?.[1] : undefined;
}
