export interface Entry {
  name: string;
  type?: string;
  data?: Buffer | string;
  mode?: number;
  size?: number;
  linkname?: string;
}

function header(entry: Entry, size: number): Buffer {
  const block = Buffer.alloc(512);
  block.write(entry.name.slice(0, 100), 0, "utf8");
  block.write(`${(entry.mode ?? 0o644).toString(8).padStart(7, "0")}\0`, 100, "latin1");
  block.write("0000000\0", 108, "latin1");
  block.write("0000000\0", 116, "latin1");
  block.write(`${size.toString(8).padStart(11, "0")}\0`, 124, "latin1");
  block.write("15266210261\0", 136, "latin1");
  block.write(entry.type ?? "0", 156, "latin1");
  block.write(entry.linkname ?? "", 157, "utf8");
  block.write("ustar\u000000", 257, "latin1");
  block.fill(0x20, 148, 156);
  let sum = 0;
  for (const byte of block) sum += byte;
  block.write(`${sum.toString(8).padStart(6, "0")}\0 `, 148, "latin1");
  return block;
}

export function tar(entries: Entry[]): Buffer {
  const parts: Buffer[] = [];
  for (const entry of entries) {
    const data = Buffer.from(entry.data ?? "");
    parts.push(header(entry, entry.size ?? data.length), data, Buffer.alloc((512 - (data.length % 512)) % 512));
  }
  parts.push(Buffer.alloc(1024));
  return Buffer.concat(parts);
}

export function pax(records: Record<string, string>): Entry {
  let body = "";
  for (const [key, value] of Object.entries(records)) {
    const tail = ` ${key}=${value}\n`;
    let length = Buffer.byteLength(tail) + 1;
    while (String(length).length + Buffer.byteLength(tail) !== length) length++;
    body += `${length}${tail}`;
  }
  return { name: "PaxHeaders.0/x", type: "x", data: body };
}

